export type EosOscKey = (typeof EOS_OSC_KEYS)[number];

const KEY_LOOKUP = new Map(
  EOS_OSC_KEYS.map((key) => [key.toLowerCase().replace(/\s+/g, "_"), key])
);

/** Resolve user input to a canonical OSC key name (case-insensitive). */
export function resolveOscKey(input: string): string | null {
  const normalized = input.trim().replace(/\s+/g, "_").toLowerCase();
  if (normalized === "/" || normalized === "slash") {
    return "\\";
  }
  return KEY_LOOKUP.get(normalized) ?? null;
}
